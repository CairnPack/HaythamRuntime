using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace Haytham.Runtime.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class RuntimeInputGenerator : IIncrementalGenerator {
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var catalogs = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Haytham.Runtime.Inputs.InputCatalogAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, cancellation) => Analyze(attributeContext, cancellation));

        context.RegisterSourceOutput(catalogs, static (sourceContext, catalog) => {
            foreach (var diagnostic in catalog.Diagnostics) {
                sourceContext.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (catalog.Diagnostics.Count == 0) {
                sourceContext.AddSource(catalog.HintName, catalog.Source);
            }
        });
    }

    private static Catalog Analyze(GeneratorAttributeSyntaxContext context, CancellationToken cancellation) {
        var type = (INamedTypeSymbol)context.TargetSymbol;
        var diagnostics = new List<DiagnosticInfo>();
        CheckDeclaration(type, diagnostics, cancellation);
        var entries = ReadEntries(type, context.SemanticModel.Compilation, diagnostics, cancellation);
        var jsonContext = (INamedTypeSymbol)context.Attributes[0].ConstructorArguments[0].Value!;
        var encodedName = Convert.ToBase64String(Encoding.UTF8.GetBytes(type.ToDisplayString()))
            .TrimEnd('=').Replace('+', '-').Replace('/', '_');
        return new Catalog("RuntimeInputs." + encodedName + ".g.cs",
            diagnostics.Count == 0 ? Emit(type, jsonContext, entries) : string.Empty, diagnostics);
    }

    private static void CheckDeclaration(INamedTypeSymbol type, List<DiagnosticInfo> diagnostics, CancellationToken cancellation) {
        foreach (var reference in type.DeclaringSyntaxReferences) {
            var syntax = (ClassDeclarationSyntax)reference.GetSyntax(cancellation);
            if (!type.IsStatic || type.ContainingType is not null || !syntax.Modifiers.Any(SyntaxKind.PartialKeyword)) {
                diagnostics.Add(new DiagnosticInfo(DiagnosticDescriptors.InvalidInputCatalog,
                    LocationInfo.From(syntax.Identifier.GetLocation()), type.Name));
            }
        }
    }

    private static List<Entry> ReadEntries(INamedTypeSymbol catalog, Compilation compilation,
        List<DiagnosticInfo> diagnostics, CancellationToken cancellation) {
        var entries = new List<Entry>();
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var field in catalog.GetMembers().OfType<IFieldSymbol>()) {
            if (!field.IsStatic || !field.IsReadOnly || field.Type is not INamedTypeSymbol type || type.Arity != 4
                || type.ContainingNamespace.ToDisplayString() != "Haytham.Runtime.Inputs"
                || type.Name is not ("TaskInput" or "CallInput")) {
                continue;
            }

            var syntax = (VariableDeclaratorSyntax)field.DeclaringSyntaxReferences[0].GetSyntax(cancellation);
            var model = compilation.GetSemanticModel(syntax.SyntaxTree);
            var creation = syntax.Initializer is null ? null : model.GetOperation(syntax.Initializer.Value, cancellation) as IObjectCreationOperation;
            var nameArgument = creation?.Arguments.FirstOrDefault(argument => argument.Parameter?.Name == "name");
            var constant = nameArgument?.Value.ConstantValue;
            if (constant is not { HasValue: true, Value: string name }) {
                diagnostics.Add(new DiagnosticInfo(DiagnosticDescriptors.InputNameNotConstant,
                    LocationInfo.From(nameArgument?.Value.Syntax.GetLocation() ?? syntax.Identifier.GetLocation()), field.Name));
                continue;
            }

            if (!names.Add(name)) {
                diagnostics.Add(new DiagnosticInfo(DiagnosticDescriptors.DuplicateInputName,
                    LocationInfo.From(syntax.Identifier.GetLocation()), name));
            }

            entries.Add(new Entry(field.Name, name, type.Name == "TaskInput" ? "Task" : "Call",
                type.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                type.TypeArguments[3].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));
        }

        return entries;
    }

    private static string Emit(INamedTypeSymbol type, INamedTypeSymbol jsonContext, List<Entry> entries) {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// 由 Haytham.Runtime.Generators.RuntimeInputGenerator 生成，请勿手动修改。");
        builder.AppendLine("#nullable enable");
        if (!type.ContainingNamespace.IsGlobalNamespace) {
            builder.AppendLine($"namespace {type.ContainingNamespace.ToDisplayString()};");
        }

        builder.AppendLine($"partial class @{type.Name} {{");
        EmitRegister(builder, jsonContext, entries);
        builder.AppendLine();
        EmitManifest(builder, entries);
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void EmitRegister(StringBuilder builder, INamedTypeSymbol jsonContext, List<Entry> entries) {
        builder.AppendLine("    public static void Register(global::Haytham.Runtime.Events.Registry registry) {");
        var contextName = jsonContext.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        foreach (var entry in entries) {
            builder.AppendLine($"        @{entry.FieldName}.Register(registry,");
            builder.AppendLine($"            {JsonMetadata(contextName, entry.InputType)},");
            builder.AppendLine($"            {JsonMetadata(contextName, entry.ReplyType)});");
        }
        builder.AppendLine("    }");
    }

    private static string JsonMetadata(string contextName, string typeName) {
        var message = Literal($"JSON 上下文 {contextName} 缺少类型 {typeName} 的元数据。");
        return $"(global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{typeName}>)({contextName}.Default.GetTypeInfo(typeof({typeName}))"
            + $" ?? throw new global::Haytham.Runtime.RuntimeContractException({message}))";
    }

    private static void EmitManifest(StringBuilder builder, List<Entry> entries) {
        builder.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<global::Haytham.Runtime.Inputs.InputManifestEntry> Manifest { get; } = [");
        foreach (var entry in entries) {
            builder.AppendLine($"        new({Literal(entry.Name)}, global::Haytham.Runtime.Inputs.InputKind.{entry.Kind}, typeof({entry.InputType}), typeof({entry.ReplyType}), {Literal(entry.FieldName)}),");
        }
        builder.AppendLine("    ];");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
    private sealed record Entry(string FieldName, string Name, string Kind, string InputType, string ReplyType);
    private sealed record Catalog(string HintName, string Source, List<DiagnosticInfo> Diagnostics);
}
