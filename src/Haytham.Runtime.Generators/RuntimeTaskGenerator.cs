using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Haytham.Runtime.Generators;

/// <summary>
/// 为具体 Task 生成强类型的提交和子调用入口。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class RuntimeTaskGenerator : IIncrementalGenerator {
    private const string TaskMetadataName = "Haytham.Runtime.Tasks.RuntimeTask`2";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers
            | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
            predicate: static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
            transform: static (syntaxContext, cancellationToken) => Analyze(syntaxContext, cancellationToken));

        context.RegisterSourceOutput(candidates, static (sourceContext, candidate) => {
            if (candidate is null) {
                return;
            }

            if (candidate.Diagnostic is { } diagnostic) {
                sourceContext.ReportDiagnostic(diagnostic.ToDiagnostic());
            } else {
                sourceContext.AddSource(candidate.HintName, candidate.Source);
            }
        });
    }

    private static TaskCandidate? Analyze(GeneratorSyntaxContext context, CancellationToken cancellationToken) {
        var declaration = (ClassDeclarationSyntax)context.Node;
        var type = (INamedTypeSymbol)context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken)!;
        if (type.IsAbstract) {
            return null;
        }

        // 同一个 partial 类型可能在多个声明上写基类，只处理其中一个。
        var declarations = type.DeclaringSyntaxReferences
            .Select(reference => (ClassDeclarationSyntax)reference.GetSyntax(cancellationToken)).ToList();
        var first = declarations.First(static syntax => syntax.BaseList is not null);
        if (first.SyntaxTree != declaration.SyntaxTree || first.Span != declaration.Span) {
            return null;
        }

        var taskType = context.SemanticModel.Compilation.GetTypeByMetadataName(TaskMetadataName);
        if (taskType is null) {
            return null;
        }

        var baseType = type.BaseType;
        while (baseType is not null && !SymbolEqualityComparer.Default.Equals(baseType.OriginalDefinition, taskType)) {
            baseType = baseType.BaseType;
        }

        if (baseType is null) {
            return null;
        }

        if (declarations.Any(static syntax => !syntax.Modifiers.Any(SyntaxKind.PartialKeyword))) {
            return Fail(DiagnosticDescriptors.TaskNotPartial, type, declaration);
        }

        if (!type.IsSealed) {
            return Fail(DiagnosticDescriptors.TaskNotSealed, type, declaration);
        }

        if (type.Arity != 0) {
            return Fail(DiagnosticDescriptors.GenericTask, type, declaration);
        }

        for (var outer = type.ContainingType; outer is not null; outer = outer.ContainingType) {
            foreach (var reference in outer.DeclaringSyntaxReferences) {
                var outerDeclaration = (TypeDeclarationSyntax)reference.GetSyntax(cancellationToken);
                if (!outerDeclaration.Modifiers.Any(SyntaxKind.PartialKeyword)) {
                    return Fail(DiagnosticDescriptors.TaskContainingTypeNotPartial, outer, outerDeclaration);
                }
            }
        }

        var namespaceName = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();
        // 类型全名可能包含关键字转义和泛型标点，编码后用于生成文件名。
        var encodedName = Convert.ToBase64String(Encoding.UTF8.GetBytes(type.ToDisplayString(TypeFormat)))
            .TrimEnd('=').Replace('+', '-').Replace('/', '_');
        var hintName = "RuntimeTask." + encodedName + ".g.cs";
        return new TaskCandidate(hintName, Emit(type, baseType, namespaceName), Diagnostic: null);

        static TaskCandidate Fail(DiagnosticDescriptor descriptor, INamedTypeSymbol invalidType,
            TypeDeclarationSyntax syntax) =>
            new(string.Empty, string.Empty, new DiagnosticInfo(descriptor,
                LocationInfo.From(syntax.Identifier.GetLocation()),
                invalidType.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat)));
    }

    private static string Emit(INamedTypeSymbol type, INamedTypeSymbol baseType, string namespaceName) {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// 由 Haytham.Runtime.Generators.RuntimeTaskGenerator 生成，请勿手动修改。");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        if (namespaceName.Length != 0) {
            builder.AppendLine($"namespace {namespaceName};");
            builder.AppendLine();
        }

        var containingTypes = new Stack<INamedTypeSymbol>();
        for (var outer = type.ContainingType; outer is not null; outer = outer.ContainingType) {
            containingTypes.Push(outer);
        }

        var indent = string.Empty;
        foreach (var outer in containingTypes) {
            var kind = outer.IsRecord
                ? (outer.TypeKind == TypeKind.Struct ? "record struct" : "record class")
                : outer.TypeKind switch {
                    TypeKind.Struct => "struct",
                    TypeKind.Interface => "interface",
                    _ => "class"
                };
            var parameters = outer.Arity == 0
                ? string.Empty
                : "<" + string.Join(", ", outer.TypeParameters.Select(static parameter => Identifier(parameter.Name))) + ">";
            builder.AppendLine($"{indent}partial {kind} {Identifier(outer.Name)}{parameters} {{");
            indent += "    ";
        }

        builder.AppendLine($"{indent}partial class {Identifier(type.Name)} {{");
        indent += "    ";
        var taskName = type.ToDisplayString(TypeFormat);
        var inputName = baseType.TypeArguments[0].ToDisplayString(TypeFormat);
        var resultName = baseType.TypeArguments[1].ToDisplayString(TypeFormat);
        var arguments = $"{taskName}, {inputName}, {resultName}";
        builder.AppendLine(
            $"{indent}public static global::Haytham.Runtime.Tasks.TaskRun<{resultName}> Submit(global::Haytham.Runtime.RuntimeHost host, {inputName} input,");
        builder.AppendLine(
            $"{indent}    global::System.String? queueKey = null, global::Haytham.Runtime.Tasks.ITaskOutputSink<{resultName}>? output = null, global::System.Threading.CancellationToken cancellation = default)");
        builder.AppendLine($"{indent}    => host.Submit<{arguments}>(input, queueKey, output, cancellation);");
        builder.AppendLine();
        builder.AppendLine(
            $"{indent}public static global::Haytham.Runtime.Tasks.TaskRun<{resultName}> Submit(global::Haytham.Runtime.Modules.ModuleWorkPort port, {inputName} input,");
        builder.AppendLine(
            $"{indent}    global::System.String? queueKey = null, global::Haytham.Runtime.Tasks.ITaskOutputSink<{resultName}>? output = null, global::System.Threading.CancellationToken cancellation = default)");
        builder.AppendLine($"{indent}    => port.Submit<{arguments}>(input, queueKey, output, cancellation);");
        builder.AppendLine();
        builder.AppendLine(
            $"{indent}public static global::System.Threading.Tasks.ValueTask<{resultName}> InvokeAsync(global::Haytham.Runtime.Work.WorkScope work, {inputName} input)");
        builder.AppendLine($"{indent}    => work.InvokeAsync<{arguments}>(input);");

        for (var depth = 0; depth <= containingTypes.Count; depth++) {
            indent = indent.Substring(0, indent.Length - 4);
            builder.AppendLine($"{indent}}}");
        }

        return builder.ToString();
    }

    private static string Identifier(string name) => "@" + name;

    private sealed record TaskCandidate(string HintName, string Source, DiagnosticInfo? Diagnostic);
}
