using Haytham.Runtime.Generators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Testing;
using Xunit;

namespace Haytham.Runtime.Generators.Tests;

public sealed partial class GeneratorTests {
    private const string InputSupport = """
        using System;
        using System.Text.Json.Serialization.Metadata;
        using Haytham.Runtime.Calls;
        using Haytham.Runtime.Inputs;
        using Haytham.Runtime.Tasks;
        namespace Acme;
        internal sealed class Json {
            public static Json Default { get; } = new();
            public JsonTypeInfo? GetTypeInfo(Type type) => null;
        }
        internal sealed class ReadCall : RuntimeCall<int, int> {
            protected override int Invoke(int input) => input;
        }
        internal sealed class Job : RuntimeTask<int, int> {
            public override TaskExitPolicy ExitPolicy => TaskExitPolicy.Wait;
            protected override System.Threading.Tasks.ValueTask<int> ExecuteAsync(TaskEvent<int, int> e) => new(e.Input);
        }
        """;

    [Theory]
    [InlineData("HRT0012", "[InputCatalog(typeof(Json))] internal static class {|#0:Inputs|} { }")]
    [InlineData("HRT0012", "[InputCatalog(typeof(Json))] internal partial class {|#0:Inputs|} { }")]
    [InlineData("HRT0012", "internal partial class Outer { [InputCatalog(typeof(Json))] internal static partial class {|#0:Inputs|} { } }")]
    [InlineData("HRT0012", "internal class Outer { [InputCatalog(typeof(Json))] internal static partial class {|#0:Inputs|} { } }")]
    [InlineData("HRT0013", """
        [InputCatalog(typeof(Json))] internal static partial class Inputs {
            private static string Name => "read";
            public static readonly CallInput<ReadCall, int, int, int> Read =
                new(name: {|#0:Name|}, mapResult: static value => new InputResult<int>.Success(value));
        }
        """)]
    [InlineData("HRT0014", """
        [InputCatalog(typeof(Json))] internal static partial class Inputs {
            public static readonly TaskInput<Job, int, int, int> First =
                new(name: "same", mapResult: static value => new InputResult<int>.Success(value));
            public static readonly CallInput<ReadCall, int, int, int> {|#0:Second|} =
                new(name: "same", mapResult: static value => new InputResult<int>.Success(value));
        }
        """)]
    public async Task InputDiagnostics(string id, string declaration) {
        var test = CreateTest<RuntimeInputGenerator>(InputSupport + "\n" + declaration);
        test.ExpectedDiagnostics.Add(new DiagnosticResult(id, DiagnosticSeverity.Error).WithLocation(0));
        await test.RunAsync(TestContext.Current.CancellationToken);
    }

    [Fact]
    public async Task InputRegistrationAndManifest() {
        var test = CreateTest<RuntimeInputGenerator>(InputSupport + """

            [InputCatalog(typeof(Json))]
            internal static partial class Inputs {
                private const string Prefix = "probe.";
                public static readonly TaskInput<Job, int, int, int> Task =
                    new(name: Prefix + "task", queueKey: static _ => "shared", mapResult: static value => new InputResult<int>.Success(value));
                public static readonly CallInput<ReadCall, int, int, int> Call =
                    new(name: "probe.call", mapResult: static value => new InputResult<int>.Success(value));
            }
            """);
        var hint = "RuntimeInputs." + Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes("Acme.Inputs"))
            .TrimEnd('=').Replace('+', '-').Replace('/', '_') + ".g.cs";
        test.TestState.GeneratedSources.Add((typeof(RuntimeInputGenerator), hint, """
            // <auto-generated/>
            // 由 Haytham.Runtime.Generators.RuntimeInputGenerator 生成，请勿手动修改。
            #nullable enable
            namespace Acme;
            partial class @Inputs {
                public static void Register(global::Haytham.Runtime.Events.Registry registry) {
                    @Task.Register(registry,
                        (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<int>)(global::Acme.Json.Default.GetTypeInfo(typeof(int)) ?? throw new global::Haytham.Runtime.RuntimeContractException("JSON 上下文 global::Acme.Json 缺少类型 int 的元数据。")),
                        (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<int>)(global::Acme.Json.Default.GetTypeInfo(typeof(int)) ?? throw new global::Haytham.Runtime.RuntimeContractException("JSON 上下文 global::Acme.Json 缺少类型 int 的元数据。")));
                    @Call.Register(registry,
                        (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<int>)(global::Acme.Json.Default.GetTypeInfo(typeof(int)) ?? throw new global::Haytham.Runtime.RuntimeContractException("JSON 上下文 global::Acme.Json 缺少类型 int 的元数据。")),
                        (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<int>)(global::Acme.Json.Default.GetTypeInfo(typeof(int)) ?? throw new global::Haytham.Runtime.RuntimeContractException("JSON 上下文 global::Acme.Json 缺少类型 int 的元数据。")));
                }

                public static global::System.Collections.Generic.IReadOnlyList<global::Haytham.Runtime.Inputs.InputManifestEntry> Manifest { get; } = [
                    new("probe.task", global::Haytham.Runtime.Inputs.InputKind.Task, typeof(int), typeof(int), "Task"),
                    new("probe.call", global::Haytham.Runtime.Inputs.InputKind.Call, typeof(int), typeof(int), "Call"),
                ];
            }
            """.ReplaceLineEndings() + Environment.NewLine));
        await test.RunAsync(TestContext.Current.CancellationToken);
    }
}
