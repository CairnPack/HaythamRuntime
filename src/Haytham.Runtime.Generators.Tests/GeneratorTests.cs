    private static CSharpSourceGeneratorTest<TGenerator, DefaultVerifier> CreateTest<TGenerator>(
        string source, string version = "1.2.3", bool application = false) where TGenerator : new() {
        var test = new CSharpSourceGeneratorTest<TGenerator, DefaultVerifier> {
            TestCode = source,
            ReferenceAssemblies = Net10,
            CompilerDiagnostics = CompilerDiagnostics.Errors,
        };
        test.TestState.AdditionalReferences.Add(MetadataReference.CreateFromFile(typeof(IRuntimeModule).Assembly.Location));
        test.TestState.AnalyzerConfigFiles.Add(("/.globalconfig", $"""
            is_global = true
            build_property.PackageId = Acme.Package
            build_property.Version = {version}
            build_property.Authors = Alice, Bob, Carol
            build_property.Description = Test module
            build_property.HaythamRuntimeApplication = {application.ToString().ToLowerInvariant()}
            """));
        test.SolutionTransforms.Add((solution, projectId) => solution.WithProjectAssemblyName(projectId, "Acme.Install"));
        return test;
    }

    private static async Task<PortableExecutableReference> CompileReference(string name, string source,
        params MetadataReference[] dependencies) {
        var references = await Net10.ResolveAsync(LanguageNames.CSharp, TestContext.Current.CancellationToken);
        var compilation = CSharpCompilation.Create(name,
            [CSharpSyntaxTree.ParseText(source)],
            references.Add(MetadataReference.CreateFromFile(typeof(IRuntimeModule).Assembly.Location)).AddRange(dependencies),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        using var stream = new MemoryStream();
        var result = compilation.Emit(stream);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        return MetadataReference.CreateFromImage(stream.ToArray());
    }
