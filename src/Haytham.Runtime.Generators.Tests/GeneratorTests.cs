    [Fact]
    public async Task O03_ApplicationDependencyOrder() {
        var storage = await CompileReference("Storage", """
            using Haytham.Runtime.Modules;
            [assembly: RuntimeModuleManifest(typeof(Storage.Entry))]
            namespace Storage;
            internal sealed class MainModule : IRuntimeModule {
                public void Connect(Haytham.Runtime.Modules.ModuleWiring wiring) { }
            }
            public static class Entry {
                public const string Id = "Storage";
                public static ModuleDefinition Definition { get; } = new(
                    Id, "1.0.0", [], "Storage", [], [], static capabilities => new MainModule());
            }
            """);
        var install = await CompileReference("Install", """
            using Haytham.Runtime.Modules;
            [assembly: RuntimeModuleManifest(typeof(Install.Entry))]
            namespace Install;
            internal sealed class MainModule : IRuntimeModule {
                public void Connect(Haytham.Runtime.Modules.ModuleWiring wiring) { }
            }
            public static class Entry {
                public const string Id = "Install";
                public const string Dependency0 = Storage.Entry.Id;
                public static ModuleDefinition Definition { get; } = new(
                    Id, "1.0.0", [], "Install", [Dependency0], [], static capabilities => new MainModule());
            }
            """, storage);
        var test = CreateTest<RuntimeModuleGenerator>(ModuleSource, application: true);
        test.TestState.AdditionalReferences.Add(install);
        test.TestState.AdditionalReferences.Add(storage);
        test.TestState.GeneratedSources.Add((typeof(RuntimeModuleGenerator), "RuntimeModuleManifest.g.cs",
            Manifest.Replace("public const string Id = \"Acme.Package\";",
                "public const string Id = \"Acme.Package\";" + Environment.NewLine
                + "    public const string Dependency0 = \"Install\";" + Environment.NewLine
                + "    public const string Dependency1 = \"Storage\";")
                .Replace("Dependencies: []", "Dependencies: [Dependency0, Dependency1]") + Environment.NewLine));
        test.TestState.GeneratedSources.Add((typeof(RuntimeModuleGenerator), "RuntimeApplication.g.cs", """
            // <auto-generated/>
            // 由 Haytham.Runtime.Generators.RuntimeModuleGenerator 生成，请勿手动修改。
            #nullable enable

            namespace Haytham.Runtime.Generated;

            internal static class RuntimeApplication {

                internal static global::Haytham.Runtime.RuntimeHost Create(global::Haytham.Runtime.RuntimeCapabilities capabilities)
                    => global::Haytham.Runtime.RuntimeHost.Create(
                        [
                            global::Storage.Entry.Definition,
                            global::Install.Entry.Definition,
                            global::Haytham.Runtime.Generated.Exports.M_Acme_dInstall.Definition,
                        ],
                        capabilities);

            }
            """.ReplaceLineEndings() + Environment.NewLine));
        await test.RunAsync(TestContext.Current.CancellationToken);
    }

    [Fact]
    public async Task O04_NestedTaskMethods() {
        var test = CreateTest<RuntimeTaskGenerator>("""
            using Haytham.Runtime;
            using Haytham.Runtime.Modules;
            using Haytham.Runtime.Tasks;
            using Haytham.Runtime.Work;
            namespace Acme;
            internal partial class Outer {
                internal partial class Inner {
                    internal sealed partial class Job : RuntimeTask<int, int> {
            """ + TaskMembers + """
                    }
                }
            }
            internal static class Calls {
                internal static void Check(RuntimeHost host, ModuleWorkPort port, WorkScope work) {
                    TaskRun<int> fromHost = Outer.Inner.Job.Submit(host, 1);
                    TaskRun<int> fromPort = Outer.Inner.Job.Submit(port, 2);
                    System.Threading.Tasks.ValueTask<int> child = Outer.Inner.Job.InvokeAsync(work, 3);
                }
            }
            """);
        var hint = "RuntimeTask." + Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes("global::Acme.Outer.Inner.Job"))
            .TrimEnd('=').Replace('+', '-').Replace('/', '_') + ".g.cs";
        test.TestState.GeneratedSources.Add((typeof(RuntimeTaskGenerator), hint, """
            // <auto-generated/>
            // 由 Haytham.Runtime.Generators.RuntimeTaskGenerator 生成，请勿手动修改。
            #nullable enable

            namespace Acme;

            partial class @Outer {
                partial class @Inner {
                    partial class @Job {
                        public static global::Haytham.Runtime.Tasks.TaskRun<global::System.Int32> Submit(global::Haytham.Runtime.RuntimeHost host, global::System.Int32 input,
                            global::System.String? queueKey = null, global::Haytham.Runtime.Tasks.ITaskOutputSink<global::System.Int32>? output = null, global::System.Threading.CancellationToken cancellation = default)
                            => host.Submit<global::Acme.Outer.Inner.Job, global::System.Int32, global::System.Int32>(input, queueKey, output, cancellation);

                        public static global::Haytham.Runtime.Tasks.TaskRun<global::System.Int32> Submit(global::Haytham.Runtime.Modules.ModuleWorkPort port, global::System.Int32 input,
                            global::System.String? queueKey = null, global::Haytham.Runtime.Tasks.ITaskOutputSink<global::System.Int32>? output = null, global::System.Threading.CancellationToken cancellation = default)
                            => port.Submit<global::Acme.Outer.Inner.Job, global::System.Int32, global::System.Int32>(input, queueKey, output, cancellation);

                        public static global::System.Threading.Tasks.ValueTask<global::System.Int32> InvokeAsync(global::Haytham.Runtime.Work.WorkScope work, global::System.Int32 input)
                            => work.InvokeAsync<global::Acme.Outer.Inner.Job, global::System.Int32, global::System.Int32>(input);
                    }
                }
            }
            """.ReplaceLineEndings() + Environment.NewLine));
        await test.RunAsync(TestContext.Current.CancellationToken);
    }

