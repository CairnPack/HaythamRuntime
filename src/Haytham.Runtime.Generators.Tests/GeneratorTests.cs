    [InlineData("D14", "HRT0011", "class {|#0:Outer|} { internal partial class Inner { internal sealed partial class T : RuntimeTask<int, int> { TASK_MEMBERS } } }")]
    public async Task Diagnostics(string scenario, string id, string source) {
        var input = "using Haytham.Runtime.Modules; using Haytham.Runtime.Tasks;\n"
            + source.Replace("TASK_MEMBERS", TaskMembers).Replace("MEMBERS", ModuleMembers);
        // 两类生成器分别测试，避免无模块项目的空清单干扰 Task 诊断。
        if (scenario is "D10" or "D11" or "D12" or "D13" or "D14") {
            var test = CreateTest<RuntimeTaskGenerator>(input);
            test.ExpectedDiagnostics.Add(new DiagnosticResult(id, DiagnosticSeverity.Error).WithLocation(0));
            await test.RunAsync(TestContext.Current.CancellationToken);
        } else {
            var test = CreateTest<RuntimeModuleGenerator>(input);
            test.TestBehaviors = TestBehaviors.SkipGeneratedSourcesCheck;
            test.ExpectedDiagnostics.Add(new DiagnosticResult(id, DiagnosticSeverity.Error).WithLocation(0));
            if (scenario == "D08") {
                test.ExpectedDiagnostics.Add(new DiagnosticResult(id, DiagnosticSeverity.Error).WithLocation(1));
            }
            await test.RunAsync(TestContext.Current.CancellationToken);
        }
    }

